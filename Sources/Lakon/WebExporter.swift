import AVFoundation
import Foundation
import LakonCore

/// "Export for Web (itch.io)": writes `<Title>-web/` (index.html, lakon.js, data.js, img/, audio/, effects/) and
/// `<Title>-web.zip` with index.html at the zip root, which is what itch.io's HTML upload expects.
///
/// - The runtime is Lakon's own JavaScript port (web/*.js), not MZ's rmmz_*.js.
/// - Data goes into data.js (`window.LAKON_GAME = …`) so the game also opens from a local folder.
/// - Ogg Vorbis is decoded with stb_vorbis and re-encoded as AAC (.m4a) because not every browser decodes Ogg;
///   RPG Maker's LOOPSTART/LOOPLENGTH tags are kept as loop points (seconds) in the audio manifest.
enum WebExporter {
    static let runtimeFiles = ["core-data.js", "core-world.js", "core-battle.js", "core-script.js", "ui.js", "audio.js",
                               "game.js", "menus.js", "battle.js", "effects.js", "boot.js"]

    /// web/ next to the app (build-app.sh copies it into Contents/Resources/web), else the source checkout.
    static var runtimeDir: URL? {
        let fm = FileManager.default
        if let r = Bundle.main.resourceURL?.appendingPathComponent("web"), fm.fileExists(atPath: r.appendingPathComponent("game.js").path) { return r }
        let src = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent().appendingPathComponent("web")
        return fm.fileExists(atPath: src.appendingPathComponent("game.js").path) ? src : nil
    }

    struct Report { var folder: URL; var zip: URL; var transcoded = 0; var copiedAudio = 0; var images = 0; var warnings: [String] = [] }

    static func export(project: Project, to dir: URL, makeZip: Bool = true) throws -> Report {
        let fm = FileManager.default
        guard let rt = runtimeDir else { throw ExportError.missingRuntime }
        let safe = project.system.gameTitle.components(separatedBy: CharacterSet.alphanumerics.union(.init(charactersIn: " -_")).inverted).joined()
            .trimmingCharacters(in: .whitespaces)
        let name = (safe.isEmpty ? "Game" : safe) + "-web"
        let out = dir.appendingPathComponent(name)
        if fm.fileExists(atPath: out.path) { try fm.removeItem(at: out) }
        try fm.createDirectory(at: out, withIntermediateDirectories: true)
        var report = Report(folder: out, zip: dir.appendingPathComponent(name + ".zip"))

        // Runtime: one concatenated script.
        var js = "// Lakon web runtime — generated by Lakon's Export for Web.\n"
        for f in runtimeFiles {
            let u = rt.appendingPathComponent(f)
            guard let s = try? String(contentsOf: u, encoding: .utf8) else { if f == "effects.js" { continue }; throw ExportError.missingRuntime }
            js += "\n// ---- \(f) ----\n" + s + "\n"
        }
        try js.write(to: out.appendingPathComponent("lakon.js"), atomically: true, encoding: .utf8)
        var html = try String(contentsOf: rt.appendingPathComponent("index.html"), encoding: .utf8)
        html = html.replacingOccurrences(of: "<title>Lakon Game</title>", with: "<title>\(htmlEscape(project.system.gameTitle))</title>")

        // Images (copied as-is; MZ layouts).
        let root = project.root
        for folder in Project.assetFolders where folder.hasPrefix("img/") || folder.hasPrefix("effects") {
            let src = root.appendingPathComponent(folder)
            guard let files = try? fm.contentsOfDirectory(atPath: src.path), !files.isEmpty else { continue }
            let dst = out.appendingPathComponent(folder)
            try fm.createDirectory(at: dst, withIntermediateDirectories: true)
            for f in files where !f.hasPrefix(".") {
                var isDir: ObjCBool = false
                guard fm.fileExists(atPath: src.appendingPathComponent(f).path, isDirectory: &isDir), !isDir.boolValue else { continue }
                try fm.copyItem(at: src.appendingPathComponent(f), to: dst.appendingPathComponent(f))
                if f.lowercased().hasSuffix(".png") { report.images += 1 }
            }
        }
        let hasEffects = !((try? fm.contentsOfDirectory(atPath: out.appendingPathComponent("effects").path)) ?? []).filter { $0.hasSuffix(".efkefc") }.isEmpty
        let ef = rt.appendingPathComponent("effekseer")
        if hasEffects, fm.fileExists(atPath: ef.appendingPathComponent("effekseer.min.js").path) {
            try fm.copyItem(at: ef, to: out.appendingPathComponent("effekseer"))
            html = html.replacingOccurrences(of: "<!--EFFEKSEER-->", with: "<script src=\"effekseer/effekseer.min.js\"></script>")
        } else if hasEffects {
            report.warnings.append("The project has Effekseer effects but the Effekseer web runtime isn't bundled with this Lakon; stand-ins are drawn instead.")
        }
        try html.write(to: out.appendingPathComponent("index.html"), atomically: true, encoding: .utf8)

        // Audio + manifest. Ogg files are decoded and re-encoded in parallel.
        var manifest: [String: [String: Any]] = [:]
        struct Job { let folder: String; let base: String; let src: URL; let dst: URL }
        var jobs: [Job] = []
        for folder in ["bgm", "bgs", "me", "se"] {
            let src = root.appendingPathComponent("audio/\(folder)")
            let dst = out.appendingPathComponent("audio/\(folder)")
            let files = ((try? fm.contentsOfDirectory(atPath: src.path)) ?? []).sorted()
            guard !files.isEmpty else { continue }
            try fm.createDirectory(at: dst, withIntermediateDirectories: true)
            var seen = Set<String>()
            for f in files {
                let ext = (f as NSString).pathExtension.lowercased(), base = (f as NSString).deletingPathExtension
                guard ["ogg", "m4a", "wav", "mp3", "aac"].contains(ext), !seen.contains(base) else { continue }
                seen.insert(base)
                if ext == "ogg" { jobs.append(Job(folder: folder, base: base, src: src.appendingPathComponent(f), dst: dst.appendingPathComponent(base + ".m4a"))); continue }
                try fm.copyItem(at: src.appendingPathComponent(f), to: dst.appendingPathComponent(f))
                manifest["\(folder)/\(base)"] = ["file": "audio/\(folder)/\(f.addingPercentEncoding(withAllowedCharacters: .urlPathAllowed) ?? f)"]
                report.copiedAudio += 1
            }
        }
        let lock = NSLock()
        DispatchQueue.concurrentPerform(iterations: jobs.count) { i in
            let j = jobs[i]
            guard let d = AudioPlayer.decodeOgg(j.src) else { lock.lock(); report.warnings.append("Couldn't decode \(j.folder)/\(j.src.lastPathComponent)"); lock.unlock(); return }
            do { try writeAAC(d.buffer, to: j.dst) } catch {
                lock.lock(); report.warnings.append("Couldn't encode \(j.folder)/\(j.src.lastPathComponent): \(error.localizedDescription)"); lock.unlock(); return
            }
            var entry: [String: Any] = ["file": "audio/\(j.folder)/\((j.base + ".m4a").addingPercentEncoding(withAllowedCharacters: .urlPathAllowed) ?? j.base)"]
            let rate = d.buffer.format.sampleRate
            if let ls = d.loopStart, let ll = d.loopLength, ll > 0 { entry["loopStart"] = Double(ls) / rate; entry["loopLength"] = Double(ll) / rate }
            lock.lock(); manifest["\(j.folder)/\(j.base)"] = entry; report.transcoded += 1; lock.unlock()
        }

        // Data: every data/*.json as parsed JSON, plus plugins (plugins.json order, like the Mac player).
        var data: [String: Any] = [:]
        for f in ((try? fm.contentsOfDirectory(atPath: project.dataURL.path)) ?? []) where f.hasSuffix(".json") {
            if let d = try? Data(contentsOf: project.dataURL.appendingPathComponent(f)), let o = try? JSONSerialization.jsonObject(with: d, options: [.fragmentsAllowed]) { data[f] = o }
        }
        data["__plugins"] = plugins(project)
        var preload: [[String]] = [["system", "IconSet"]]
        if let m = project.maps[project.system.startMapId] {
            for n in project.tileset(for: m).tilesetNames where !n.isEmpty { preload.append(["tilesets", n]) }
        }
        if !project.system.title1Name.isEmpty { preload.append(["titles1", project.system.title1Name]) }
        let game: [String: Any] = ["id": project.system.gameTitle, "base": "", "data": data, "audio": manifest, "preload": preload]
        let json = try JSONSerialization.data(withJSONObject: game, options: [.sortedKeys])
        var dataJS = Data("window.LAKON_GAME = ".utf8); dataJS.append(json); dataJS.append(Data(";\n".utf8))
        try dataJS.write(to: out.appendingPathComponent("data.js"))

        // itch.io's HTML5 uploads allow at most 1,000 files (and 500 MB) per zip.
        var fileCount = 0
        if let e = fm.enumerator(at: out, includingPropertiesForKeys: [.isRegularFileKey]) {
            for case let u as URL in e where (try? u.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile) == true { fileCount += 1 }
        }
        if fileCount > 1000 { report.warnings.append("\(fileCount) files: itch.io accepts at most 1,000 per HTML5 zip — remove unused images/audio before uploading.") }
        if makeZip {
            if fm.fileExists(atPath: report.zip.path) { try fm.removeItem(at: report.zip) }
            let p = Process()
            p.executableURL = URL(fileURLWithPath: "/usr/bin/ditto")
            p.arguments = ["-c", "-k", "--norsrc", out.path, report.zip.path]
            try p.run(); p.waitUntilExit()
            if p.terminationStatus != 0 { report.warnings.append("zip failed (ditto exit \(p.terminationStatus))") }
        }
        return report
    }

    static func plugins(_ project: Project) -> [[String: Any]] {
        let dir = project.root.appendingPathComponent("plugins"), fm = FileManager.default
        var entries: [(String, Any)] = []
        if let d = try? Data(contentsOf: dir.appendingPathComponent("plugins.json")), let list = try? JSONSerialization.jsonObject(with: d) as? [[String: Any]] {
            for e in list where (e["status"] as? Bool) ?? true { if let n = e["name"] as? String { entries.append((n, e["parameters"] ?? [:])) } }
        } else {
            entries = ((try? fm.contentsOfDirectory(atPath: dir.path)) ?? []).filter { $0.hasSuffix(".js") }.sorted().map { (String($0.dropLast(3)), [String: Any]()) }
        }
        return entries.compactMap { n, params in
            guard let src = try? String(contentsOf: dir.appendingPathComponent(n + ".js"), encoding: .utf8) else { return nil }
            return ["name": n, "parameters": params, "source": src]
        }
    }

    /// AAC in an .m4a container via AVAudioFile.
    static func writeAAC(_ buffer: AVAudioPCMBuffer, to url: URL) throws {
        let f = buffer.format
        let settings: [String: Any] = [AVFormatIDKey: kAudioFormatMPEG4AAC, AVSampleRateKey: f.sampleRate,
                                       AVNumberOfChannelsKey: f.channelCount, AVEncoderBitRateKey: f.channelCount > 1 ? 160_000 : 96_000]
        let file = try AVAudioFile(forWriting: url, settings: settings, commonFormat: .pcmFormatFloat32, interleaved: false)
        try file.write(from: buffer)
    }

    static func htmlEscape(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;").replacingOccurrences(of: ">", with: "&gt;")
    }

    enum ExportError: LocalizedError {
        case missingRuntime
        var errorDescription: String? { "The web runtime (web/*.js) wasn't found next to Lakon. Rebuild with scripts/build-app.sh." }
    }
}
